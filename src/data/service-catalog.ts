/* ------------------------------- Helpers --------------------------------- */

export function catalogServiceBySlug(slug: string): CatalogService | undefined {
  return SERVICES_CATALOG.find((s) => s.slug === slug);
}

export function catalogByCategory(id: CatalogCategoryId): CatalogService[] {
  return SERVICES_CATALOG.filter((s) => s.categoryId === id);
}

export function catalogCategoryById(id: string): CatalogCategory | undefined {
  return CATALOG_CATEGORIES.find((c) => c.id === id);
}

export function catalogPopular(): CatalogService[] {
  return SERVICES_CATALOG.filter((s) => s.popular);
}

/** Layanan se-kategori (bukan dirinya), dibatasi n — untuk "layanan terkait". */
export function catalogRelated(s: CatalogService, n = 3): CatalogService[] {
  return catalogByCategory(s.categoryId)
    .filter((x) => x.slug !== s.slug)
    .slice(0, n);
}
